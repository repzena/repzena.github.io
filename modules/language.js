export let lang = initialLanguage();

function initialLanguage() {
  try {
    const savedLanguage = localStorage.getItem('form-language');
    if (savedLanguage === 'en' || savedLanguage === 'es') return savedLanguage;
  } catch {
    // Browser storage may be unavailable in private browsing contexts.
  }
  return /^es(?:-|$)/i.test(navigator.language || '') ? 'es' : 'en';
}

export function setLanguage(value) {
  if (value === 'en' || value === 'es') lang = value;
}

export function t(key) {
  return UI[lang][key] || key;
}
